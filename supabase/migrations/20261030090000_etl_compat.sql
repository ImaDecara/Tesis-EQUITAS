-- Secuencias por encima del maximo existente (1 en una base vacia).

-- Solo service_role las usa: anon/authenticated no escriben (E06).

do $$
declare
  t text;
  s text;
  next_id bigint;
begin
  foreach t in array array['address','city','data_source','debt','debtor','debtor_contact','debtor_person',
    'debtor_profile','debtor_profile_detail','person','province','tenant','tenant_user','user'] loop
    s := pg_get_serial_sequence(format('public.%I', t), 'id');
    execute format('select coalesce(max(id), 0) + 1 from public.%I', t) into next_id;
    perform setval(s, next_id, false);
    execute format('revoke all on sequence %s from public, anon, authenticated', s);
  end loop;
end $$;

